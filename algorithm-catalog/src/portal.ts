// The event as a Disasters Portal page: the TypeScript file the portal's own repo expects
// (Disasters-Learning-Portal/disasters-portal, app/site-config/event/event__<id>.ts — an
// `EventContent` from its app/site-config/types.ts).
//
// ONE generator, two callers: the app previews it, and scripts/portal_pr.mjs (the
// algorithm-catalog-portal-pr workflow) writes it into a portal checkout, registers it in
// app/site-config/event/index.ts, proves it with the portal's own Biome + tsc, and only then opens
// the portal PR. So it must stay runnable by plain Node: type-only imports, no JSON imports, no Vite.
//
// The portal's standards it follows (its types.ts and biome.json):
//   themes      = theme ids  prepare | respond | recover | resilience   (our Need)
//   categories  = its CONTENT_CATEGORIES, via data/hazards.json `portal`
//   dates       = DateString "20YY-MM-DD"
//   cards       = existing DATA__* gallery cards, via data/algorithms.json `portalData`
//   format      = Biome: 2-space, double quotes, trailing commas, 100 columns

import type { Algorithm, EventLayer, EventPage, Hazard, Need, PageImage } from "./types";

export const PORTAL_REPO = "Disasters-Learning-Portal/disasters-portal";
export const PORTAL_BRANCH = "develop";
/** The portal's default event masthead — every page this generates uses it (hero + thumbnail). */
export const PORTAL_PLACEHOLDER_IMAGE = "/img/event/template-hero.webp";
/** First line of every generated file — how the workflow knows a page is safe to regenerate. */
export const PORTAL_MARKER = "// Generated by the VEDA Algorithm Catalog";

export const NEED_LABELS: Record<Need, string> = {
  prepare: "Prepare",
  respond: "Respond",
  recover: "Recover",
  resilience: "Build Resilience",
};

export interface PortalInput {
  name: string;
  stacName: string;
  start: string;
  hazards: string[];
  locations: string[];
  layers: EventLayer[];
  page?: EventPage;
}

/** A page image once scripts/portal_pr.mjs has downloaded it into the portal checkout. */
export interface ResolvedImage extends PageImage {
  /** Site path inside the portal, e.g. /img/event/<id>__overview-1.jpg */
  src: string;
  width: number;
  height: number;
}

export interface PortalFile {
  id: string;
  constName: string;
  /** Repo-relative path inside disasters-portal. */
  path: string;
  source: string;
  /** Layers that have no portal gallery card yet — listed in the file as a comment. */
  unmapped: string[];
}

// The portal's slugs abbreviate months: hurricane-helene-sept-2024, texas-floods-july-2025.
const MONTH_ABBR: Record<string, string> = {
  january: "jan",
  february: "feb",
  march: "mar",
  april: "apr",
  june: "jun",
  september: "sept",
  october: "oct",
  november: "nov",
  december: "dec",
  august: "aug",
};

export function derivePortalId(name: string): string {
  return name
    .toLowerCase()
    .replace(/[.'’]/g, "") // "U.S." -> "us", not "u-s" (us-winter-storm-jan-2026)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .split("-")
    .map((w) => MONTH_ABBR[w] ?? w)
    .join("-");
}

export const portalIdOf = (ev: PortalInput): string => ev.page?.portalId?.trim() || derivePortalId(ev.name);

export const portalConstName = (id: string): string => `EVENT__${id.toUpperCase().replace(/-/g, "_")}`;

export const portalPath = (id: string): string => `app/site-config/event/event__${id}.ts`;

/** "DATA__SENTINEL_2_TRUE_COLOR" -> its module, app/site-config/data/data__sentinel-2-true-color. */
export const portalDataModule = (constName: string): string =>
  `@/app/site-config/data/data__${constName.replace(/^DATA__/, "").toLowerCase().replace(/_/g, "-")}`;

/**
 * Prose as the portal will print it: one line, straight double quotes made curly (the portal
 * already writes NASA’s, not NASA's) — otherwise Biome would flip the literal to single quotes and
 * `biome ci` would fail the PR on formatting. The live preview applies this too, so it shows
 * exactly the text the generated file will carry.
 */
export function typographic(text: string): string {
  return text
    .replace(/\s*\n\s*/g, " ")
    .replace(/"([^"]*)"/g, "“$1”")
    .replace(/"/g, "”");
}

/** A TS string literal in the portal's style. */
const lit = (text: string): string => JSON.stringify(typographic(text));

/** `key: value,` at `indent`, broken onto two lines the way Biome does once it passes 100 columns. */
function prop(indent: string, key: string, value: string): string {
  const one = `${indent}${key}: ${value},`;
  return one.length <= 100 ? one : `${indent}${key}:\n${indent}  ${value},`;
}

/** An array literal: inline when it fits in 100 columns, else one element per line (Biome). */
function arr(indent: string, key: string, items: string[]): string {
  const one = `${indent}${key}: [${items.join(", ")}],`;
  if (one.length <= 100) return one;
  return [`${indent}${key}: [`, ...items.map((i) => `${indent}  ${i},`), `${indent}],`].join("\n");
}

/**
 * `resolved` = the page's Drive image after scripts/portal_pr.mjs downloaded it ([] if that failed).
 * Omitted (the app's preview), the image is listed as a comment saying it will be downloaded;
 * given, a downloaded image becomes an `image` block after the intro, and a failed one is listed
 * for a human to add.
 */
export function portalEventFile(
  ev: PortalInput,
  algorithms: Algorithm[],
  hazards: Hazard[],
  datePublished: string,
  resolved?: ResolvedImage[],
): PortalFile {
  const id = portalIdOf(ev);
  const constName = portalConstName(id);
  const page = ev.page;

  const cards: string[] = [];
  const unmapped: string[] = [];
  for (const l of ev.layers) {
    const a = algorithms.find((x) => x.id === l.algorithm);
    const p = a?.products.find((x) => x.id === l.product);
    if (p?.portalData) {
      if (!cards.includes(p.portalData)) cards.push(p.portalData);
    } else {
      unmapped.push(a && p ? `${a.title} ${p.label}` : `${l.algorithm} ${l.product}`);
    }
  }

  const categories = [
    ...new Set(ev.hazards.map((h) => hazards.find((v) => v.id === h)?.portal).filter((c): c is string => !!c)),
  ];
  const region = page?.region?.trim() || ev.locations.join("; ");
  const paragraphs = (page?.intro ?? "")
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter(Boolean);
  const heroSrc = PORTAL_PLACEHOLDER_IMAGE;
  const alt = lit(`Masthead image for ${ev.name}`);
  const pending = page?.image?.url.trim() && !resolved?.some((r) => r.url === page.image?.url) ? [page.image] : [];

  const imports = [
    ...cards
      .map((c) => ({ c, mod: portalDataModule(c) }))
      .sort((a, b) => a.mod.localeCompare(b.mod))
      .map(({ c, mod }) => `import { ${c} } from "${mod}";`),
    `import type { EventContent } from "@/app/site-config/types";`,
  ];

  const body: string[] = [
    "    {",
    `      type: "text",`,
    `      heading: "Overview",`,
    arr("      ", "paragraphs", (paragraphs.length ? paragraphs : ["Overview to come."]).map(lit)),
    "    },",
  ];
  for (const img of resolved ?? []) {
    body.push(
      "    {",
      `      type: "image",`,
      prop("      ", "src", lit(img.src)),
      prop("      ", "alt", lit(img.alt)),
      `      width: ${img.width},`,
      `      height: ${img.height},`,
      ...(img.caption ? [prop("      ", "caption", lit(img.caption))] : []),
      "    },",
    );
  }
  if (cards.length > 0) {
    body.push(
      "    {",
      `      type: "sectionCardGallery",`,
      `      heading: "Event Data Gallery",`,
      "      link: {",
      `        href: "/data-gallery",`,
      `        label: "View all",`,
      "      },",
      arr("      ", "cards", cards),
      "    },",
    );
  }

  const lines = [
    `${PORTAL_MARKER} (NASA-IMPACT/veda-github-actions) from`,
    `// activation ${ev.stacName}. Regenerated on every catalog edit — to take it over by hand,`,
    "// delete these three lines first.",
    ...imports,
    "",
    `export const ${constName}: EventContent = {`,
    prop("  ", "id", lit(id)),
    "",
    `  contentType: "event",`,
    "",
    prop("  ", "title", lit(ev.name)),
    "",
  ];
  if (page?.subtitle?.trim()) lines.push(prop("  ", "description", lit(page.subtitle.trim())), "");
  lines.push(
    prop("  ", "datePublished", lit(datePublished)),
    "",
    "  thumbnailImage: {",
    `    src: "${heroSrc}",`,
    prop("    ", "alt", alt),
    "  },",
    "",
    "  mastheadImage: {",
    `    src: "${heroSrc}",`,
    prop("    ", "alt", alt),
    "  },",
    "",
    arr("  ", "themes", (page?.needs ?? []).map((n) => lit(n))),
    "",
    arr("  ", "categories", categories.map(lit)),
    "",
    prop("  ", "region", lit(region)),
    "",
    prop("  ", "startDate", lit(ev.start)),
    "",
  );
  if (page?.govLink?.trim()) {
    lines.push("  linkUSGovernment: {", `    label: "Learn more",`, prop("    ", "href", lit(page.govLink.trim())), "  },", "");
  }
  if (unmapped.length > 0) {
    lines.push("  // No portal data-gallery card yet for:", ...unmapped.map((u) => `  //   - ${u}`));
  }
  if (pending.length > 0) {
    lines.push(
      resolved
        ? "  // Could not download this Google Drive image — check its sharing, then add it by hand:"
        : "  // Google Drive image — downloaded into public/img/event/ when the portal PR is opened:",
      ...pending.map((i) => `  //   - ${i.url}`),
    );
  }
  lines.push("  body: [", ...body, "  ],", "};", "");

  return { id, constName, path: portalPath(id), source: lines.join("\n"), unmapped };
}
